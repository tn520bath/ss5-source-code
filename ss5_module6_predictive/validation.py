"""
Cross-validation reporting helpers for Module 6.

These small functions produce the held-out predictions, actuals,
fold IDs, and residuals that the report's predicted-vs-actual and
residual-plot figures need. They are kept in a separate module from
training.py because the training pipeline returns aggregated CV
metrics (mean R^2, mean RMSE) but not per-batch held-out
predictions; the figures need the per-batch outputs.

Provides:

    cv_holdout_predictions
        Returns per-batch (predicted, actual, fold_id) triples from
        the same nested-CV split that train_ridge uses, so the
        figure data is consistent with the reported CV scores.
"""

from dataclasses import dataclass

import numpy as np
from sklearn.linear_model import RidgeCV
from sklearn.model_selection import KFold, cross_val_predict
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from .training import TrainingConfig


@dataclass(frozen=True)
class CVPredictions:
    """
    Held-out cross-validation predictions for the predicted-vs-
    actual and residual figures.

    Attributes
    ----------
    predicted : np.ndarray
        Held-out predictions, shape (n_samples,). For each sample,
        this is the prediction produced when that sample was in
        the held-out fold.
    actual : np.ndarray
        The corresponding observed targets, shape (n_samples,).
        Identical to the input y.
    fold_id : np.ndarray
        Integer fold ID for each sample, shape (n_samples,). Useful
        for colouring scatter-plot points by fold or for per-fold
        residual analysis.
    residuals : np.ndarray
        predicted - actual, shape (n_samples,). Provided for
        convenience; identical to predicted - actual.
    """
    predicted: np.ndarray
    actual: np.ndarray
    fold_id: np.ndarray
    residuals: np.ndarray


def cv_holdout_predictions(
    X: np.ndarray,
    y: np.ndarray,
    config: TrainingConfig | None = None,
) -> CVPredictions:
    """
    Produce held-out CV predictions matching the outer-CV split
    used by train_ridge.

    Each held-out prediction is generated by a model that was fit on
    the corresponding training fold (with its own inner-CV alpha
    selection); the model never sees the held-out sample during
    fitting. This is methodologically identical to train_ridge's
    outer CV, so the resulting (predicted, actual) pairs are
    consistent with the R^2 and RMSE reported by train_ridge.

    Parameters
    ----------
    X : np.ndarray
        Feature matrix, shape (n_samples, n_features).
    y : np.ndarray
        Target vector, shape (n_samples,).
    config : TrainingConfig, optional
        Training configuration; defaults to the standard nested CV.

    Returns
    -------
    CVPredictions
        Held-out predictions, actuals, fold IDs, and residuals.
    """
    if config is None:
        config = TrainingConfig()

    X = np.asarray(X)
    y = np.asarray(y)

    inner_cv = KFold(
        n_splits=config.inner_cv_folds,
        shuffle=True,
        random_state=config.random_state,
    )
    pipeline = make_pipeline(
        StandardScaler(),
        RidgeCV(alphas=config.alphas, cv=inner_cv),
    )
    outer_cv = KFold(
        n_splits=config.outer_cv_folds,
        shuffle=True,
        random_state=config.random_state,
    )

    # cross_val_predict re-fits the pipeline on each training fold
    # and predicts on the held-out fold, returning one prediction
    # per sample.
    predicted = cross_val_predict(
        pipeline, X, y, cv=outer_cv, n_jobs=1
    )

    # Track which fold each sample was held out in. KFold yields
    # (train_idx, test_idx) per fold; the test indices identify
    # the held-out samples for that fold.
    fold_id = np.zeros(X.shape[0], dtype=int)
    for f, (_, test_idx) in enumerate(outer_cv.split(X)):
        fold_id[test_idx] = f

    residuals = predicted - y

    return CVPredictions(
        predicted=np.asarray(predicted, dtype=float),
        actual=np.asarray(y, dtype=float),
        fold_id=fold_id,
        residuals=np.asarray(residuals, dtype=float),
    )