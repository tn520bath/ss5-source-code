"""
Multi-image dataset generation for the synthetic data generator.

Produces a sequence of synthetic 'processing_result' messages by
calling generate_image() repeatedly. The user controls per-image
variation through a single 'variation_scale' parameter:

- variation_scale = 0 produces identical-population images, useful
  for clean experiments such as WP3 sample-size analysis.
- variation_scale > 0 produces images drawn from slightly
  different distribution parameters with variable n_fibres,
  simulating realistic feedstock variation across batches.

Variation affects only the length and width distribution parameters
and n_fibres. Reconstruction, measurement noise, and pixel_size_mm
are properties of the upstream pipeline and remain constant across
the dataset.
"""

from dataclasses import replace

import numpy as np

from .config import (
    LengthDistributionParams,
    WidthDistributionParams,
    MeasurementNoiseParams,
    QualityMetadataParams,
    DatasetGenerationParams,
    TargetGenerationParams,
    DiverseDatasetParams,
)
from .batch_assembly import generate_image


# Maximum perturbation in distribution parameters at variation_scale = 1.0.
# These constants define what 'extreme' variation means concretely.
_MAX_LENGTH_MU_DELTA = 0.40       # max +/- on length mu (log-scale)
_MAX_LENGTH_SIGMA_DELTA = 0.10    # max +/- on length sigma
_MAX_WIDTH_MU_DELTA = 0.18        # max +/- on width mu (log-scale)
_MAX_WIDTH_SIGMA_DELTA = 0.05     # max +/- on width sigma


def _perturb_length_params(
    base: LengthDistributionParams,
    variation_scale: float,
    rng: np.random.Generator,
) -> LengthDistributionParams:
    """
    Return a copy of base with mu and sigma perturbed by Gaussian
    draws scaled by variation_scale.

    sigma is constrained to remain positive.
    """
    mu_delta = rng.normal(0.0, variation_scale * _MAX_LENGTH_MU_DELTA)
    sigma_delta = rng.normal(0.0, variation_scale * _MAX_LENGTH_SIGMA_DELTA)
    return replace(
        base,
        mu=base.mu + mu_delta,
        sigma=max(base.sigma + sigma_delta, 0.05),
    )


def _perturb_width_params(
    base: WidthDistributionParams,
    variation_scale: float,
    rng: np.random.Generator,
) -> WidthDistributionParams:
    """
    Return a copy of base with mu and sigma perturbed by Gaussian
    draws scaled by variation_scale.

    sigma is constrained to remain positive.
    """
    mu_delta = rng.normal(0.0, variation_scale * _MAX_WIDTH_MU_DELTA)
    sigma_delta = rng.normal(0.0, variation_scale * _MAX_WIDTH_SIGMA_DELTA)
    return replace(
        base,
        mu=base.mu + mu_delta,
        sigma=max(base.sigma + sigma_delta, 0.02),
    )


def _draw_n_fibres(
    target: int,
    variation_scale: float,
    rng: np.random.Generator,
) -> int:
    """
    Draw n_fibres for one image.

    At variation_scale = 0, returns exactly target.
    At variation_scale > 0, draws from Poisson(target) and ensures
    n_fibres >= 1.
    """
    if variation_scale == 0.0:
        return target
    drawn = rng.poisson(lam=target)
    return max(int(drawn), 1)


def generate_dataset(
    dataset_params: DatasetGenerationParams | None = None,
    length_params: LengthDistributionParams | None = None,
    width_params: WidthDistributionParams | None = None,
    noise_params: MeasurementNoiseParams | None = None,
    quality_params: QualityMetadataParams | None = None,
    target_params: TargetGenerationParams | None = None,
    rng: np.random.Generator | None = None,
) -> list[dict]:
    """
    Generate a sequence of synthetic processing_result messages.

    Each image is generated by calling generate_image(). When
    dataset_params.variation_scale > 0, distribution parameters and
    n_fibres are perturbed independently per image; reconstruction,
    measurement noise, and pixel_size_mm remain constant across the
    dataset.

    Parameters
    ----------
    dataset_params : DatasetGenerationParams, optional
        Top-level dataset configuration. Default values are used if
        None.
    length_params, width_params, noise_params, quality_params :
        Component-level parameter dataclasses. The length and width
        params are used as 'central' values around which per-image
        perturbations are applied; the others are passed through
        unchanged.
    rng : np.random.Generator, optional
        NumPy random generator for reproducibility.

    Returns
    -------
    list[dict]
        A list of message dictionaries. Each element is a complete
        processing_result message as produced by generate_image().
        image_id values are sequential starting from 0.
    """
    if rng is None:
        rng = np.random.default_rng()

    if dataset_params is None:
        dataset_params = DatasetGenerationParams()
    if length_params is None:
        length_params = LengthDistributionParams()
    if width_params is None:
        width_params = WidthDistributionParams()
    if noise_params is None:
        noise_params = MeasurementNoiseParams()
    if quality_params is None:
        quality_params = QualityMetadataParams()
    if target_params is None:
        target_params = TargetGenerationParams()

    if not (0.0 <= dataset_params.variation_scale <= 1.0):
        raise ValueError(
            f"variation_scale must be in [0, 1], got "
            f"{dataset_params.variation_scale}."
        )

    messages = []
    for image_idx in range(dataset_params.n_images):

        # Per-image parameter perturbation
        if dataset_params.variation_scale > 0.0:
            image_length_params = _perturb_length_params(
                length_params, dataset_params.variation_scale, rng
            )
            image_width_params = _perturb_width_params(
                width_params, dataset_params.variation_scale, rng
            )
        else:
            image_length_params = length_params
            image_width_params = width_params

        n_fibres = _draw_n_fibres(
            dataset_params.target_n_fibres,
            dataset_params.variation_scale,
            rng,
        )

        message = generate_image(
            n_fibres=n_fibres,
            image_id=image_idx,
            length_params=image_length_params,
            width_params=image_width_params,
            noise_params=noise_params,
            quality_params=quality_params,
            target_params=target_params,
            rng=rng,
        )
        messages.append(message)

    return messages


def _draw_regime_grid(
    n_images: int,
    diverse_params: DiverseDatasetParams,
    rng: np.random.Generator,
) -> np.ndarray:
    """
    Draw the per-image regime values.
 
    Returns a (n_images, 4) array of values in [0, 1]; columns are
    interpreted by _scale_regime as:
        col 0 -> length_mu
        col 1 -> length_sigma
        col 2 -> width_mu
        col 3 -> p_reconstructed
 
    Latin Hypercube sampling is used when available (better space-
    filling coverage at fixed n_images); falls back to independent
    uniform draws otherwise.
    """
    if diverse_params.use_latin_hypercube:
        try:
            from scipy.stats import qmc
            sampler = qmc.LatinHypercube(d=4, seed=rng)
            return sampler.random(n=n_images)
        except ImportError:
            pass
 
    return rng.uniform(low=0.0, high=1.0, size=(n_images, 4))
 
 
def _scale_regime(
    unit_grid: np.ndarray,
    diverse_params: DiverseDatasetParams,
) -> dict:
    """
    Scale a (n_images, 4) array of unit-interval samples into the
    configured regime ranges.
 
    Returns a dict of arrays indexed by parameter name.
    """
    def _scale(col, lo, hi):
        return lo + (hi - lo) * unit_grid[:, col]
 
    return {
        "length_mu": _scale(0, *diverse_params.length_mu_range),
        "length_sigma": _scale(1, *diverse_params.length_sigma_range),
        "width_mu": _scale(2, *diverse_params.width_mu_range),
        "p_reconstructed": _scale(3, *diverse_params.p_reconstructed_range),
    }
 
 
def generate_diverse_dataset(
    diverse_params: DiverseDatasetParams | None = None,
    base_length_params: LengthDistributionParams | None = None,
    base_width_params: WidthDistributionParams | None = None,
    noise_params: MeasurementNoiseParams | None = None,
    base_quality_params: QualityMetadataParams | None = None,
    target_params: TargetGenerationParams | None = None,
    rng: np.random.Generator | None = None,
) -> list[dict]:
    """
    Generate a sequence of synthetic processing_result messages with
    designed coverage of the descriptor space.
 
    Each image is generated by sampling a per-image regime from the
    configured DiverseDatasetParams ranges and then calling
    generate_image() with overridden length, width, and reconstruction
    parameters. Measurement noise and pixel size remain at the values
    in noise_params and base_quality_params (these are upstream-
    pipeline properties, not feedstock properties; consistent with
    how generate_dataset handles them).
 
    Compared with generate_dataset(variation_scale > 0), this
    function:
      - samples descriptor space more uniformly rather than centring
        on the favourable defaults;
      - explicitly varies p_reconstructed, supporting Module 5
        confidence-gate demonstration cases;
      - uses Latin Hypercube sampling (when available) for better
        coverage at fixed n_images.
 
    Use this as the training-data source for Module 6 and as the
    sample bank for Module 5 demonstration cases. Use the standard
    generate_dataset for realistic-feedstock scenarios where
    descriptor clustering reflects production reality.
 
    Parameters
    ----------
    diverse_params : DiverseDatasetParams, optional
        Top-level configuration for diverse-dataset generation.
    base_length_params, base_width_params, base_quality_params :
        Component-level parameter dataclasses. Their mu/p values
        are overridden per image; other fields (truncation bounds,
        Beta shape parameters) pass through unchanged.
    noise_params : MeasurementNoiseParams, optional
        Measurement-noise model. Held constant across the dataset
        because it is a property of the imaging hardware, not the
        feedstock.
    target_params : TargetGenerationParams, optional
        Target generation configuration. Default leaves targets
        disabled; pass an enabled spec when generating training data.
    rng : np.random.Generator, optional
        NumPy random generator for reproducibility.
 
    Returns
    -------
    list[dict]
        A list of message dictionaries, structurally identical to
        those produced by generate_dataset. image_id values are
        sequential starting from 0.
    """
    if rng is None:
        rng = np.random.default_rng()
 
    if diverse_params is None:
        diverse_params = DiverseDatasetParams()
    if base_length_params is None:
        base_length_params = LengthDistributionParams()
    if base_width_params is None:
        base_width_params = WidthDistributionParams()
    if noise_params is None:
        noise_params = MeasurementNoiseParams()
    if base_quality_params is None:
        base_quality_params = QualityMetadataParams()
    if target_params is None:
        target_params = TargetGenerationParams()
 
    n_images = diverse_params.n_images
 
    unit_grid = _draw_regime_grid(n_images, diverse_params, rng)
    regimes = _scale_regime(unit_grid, diverse_params)
 
    messages = []
    for image_idx in range(n_images):
        image_length = replace(
            base_length_params,
            mu=float(regimes["length_mu"][image_idx]),
            sigma=float(regimes["length_sigma"][image_idx]),
        )
        image_width = replace(
            base_width_params,
            mu=float(regimes["width_mu"][image_idx]),
        )
        image_quality = replace(
            base_quality_params,
            p_reconstructed=float(regimes["p_reconstructed"][image_idx]),
        )
 
        message = generate_image(
            n_fibres=diverse_params.target_n_fibres,
            image_id=image_idx,
            length_params=image_length,
            width_params=image_width,
            noise_params=noise_params,
            quality_params=image_quality,
            target_params=target_params,
            rng=rng,
        )
        messages.append(message)
 
    return messages